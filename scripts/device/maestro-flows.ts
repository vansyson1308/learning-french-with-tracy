#!/usr/bin/env bun
/**
 * Maestro flow generator for the P3h device-acceptance suite
 * (scripts/device/acceptance.sh runs the flows). Every flow is generated
 * from the shipped content and the app's own session builders, so a content
 * or UI-string change can never leave a stale hand-written flow behind:
 *
 *   - lesson-<course>.yaml   the first lesson of every shipped course, step
 *                            by step from lessonSteps() — options are
 *                            shuffled at runtime, so answers are tapped by
 *                            their text; typed answers are ASCII-folded and
 *                            proven acceptable by the course's own grader
 *   - onboarding-<ui>.yaml   fresh install → onboarding in the vi / en UI
 *   - today / checkpoint / speech-unavailable / exam-mock / profile /
 *     export / import / screens-<ui>
 *
 *   bun scripts/device/maestro-flows.ts [--out e2e/maestro/generated]
 *
 * Maestro (Apache-2.0) runs in CI and on developer machines only; it is
 * never bundled with the app.
 */
