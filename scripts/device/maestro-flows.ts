/** The first scored checkpoint of the walk course, answered correctly from its first form. */
export function checkpointFlow(): { yaml: string; unsupported: string[] } {
  const checkpoint = checkpointFor(WALK_COURSE, SCORED_CHECKPOINT);
  if (!checkpoint) throw new Error(`missing checkpoint ${SCORED_CHECKPOINT}`);
  const unsupported: string[] = [];
  const steps = buildCheckpointSessionDefinition(WALK_COURSE, checkpoint, 0).steps;
  const lines = [
    ...header(`Sit ${SCORED_CHECKPOINT} (${steps.length} items) and reach its result.`),
    `- stopApp`,
    ...openLink(`checkpoint/${encodeURIComponent(SCORED_CHECKPOINT)}`),
    ...waitId("session-check"),
    ...answerSteps(steps, WALK_COURSE, unsupported),
    ...waitId("checkpoint-results", 15000),
    // Every item answered correctly on the first try: the result must say so.
    `- assertVisible:`,
    `    id: "checkpoint-first-try"`,
    `    text: ${q(`.*${steps.length}/${steps.length}.*`)}`,
    ...shot("checkpoint-result"),
    ``,
  ];
  return { yaml: lines.join("\n"), unsupported };
}

/**
 * No speech recogniser (the driver disables the emulator's recognition
 * services first): the spoken checkpoint and the exam speaking part must
 * say so, not start.
 */
export function speechUnavailableFlow(): string {
  const track = examTracksFor(WALK_COURSE)[0];
  return [
    ...header("Speech recogniser unavailable: spoken checkpoint and exam speaking are blocked honestly."),
    `- stopApp`,
    ...openLink(`checkpoint/${encodeURIComponent(SPOKEN_CHECKPOINT)}`),
    ...waitId("checkpoint-speech-blocked"),
    ...shot("speech-checkpoint-blocked"),
    `- stopApp`,
    ...openLink(`exam/${encodeURIComponent(track.id)}`),
    ...waitId("exam-overview"),
    ...scrollTo("exam-practice-speaking"),
    ...tapId("exam-practice-speaking"),
    ...waitId("exam-speech-unavailable"),
    ...assertId("exam-speech-skip"),
    ...shot("speech-exam-unavailable"),
    `- stopApp`,
    ``,
  ].join("\n");
}

/**
 * Exam mock: the timed reading part answered from the first mock form (a
 * fresh install has no prior mock), to the next part's intro.
 */
export function examMockFlow(): { yaml: string; unsupported: string[] } {
  const track = examTracksFor(WALK_COURSE)[0];
  const [first, second] = track.sections;
  const form = selectMockForm(track, 0);
  const steps = buildExamSectionSession({ courseId: WALK_COURSE, track, sectionId: first.id, formId: form.formId, mode: "mock", attemptSeed: 0 }).steps;
  const unsupported: string[] = [];
  const lines = [
    ...header(`Exam mock: ${track.id} ${first.id} (${steps.length} items, form ${form.formId}) to the next part's intro.`),
    `- stopApp`,
    ...openLink(`exam/${encodeURIComponent(track.id)}`),
    ...waitId("exam-overview"),
    ...scrollTo("exam-start-mock"),
    ...tapId("exam-start-mock"),
    ...waitId(`exam-mock-intro-${first.id}`),
    ...shot("exam-mock-intro"),
    ...tapId("exam-mock-start-section"),
    ...waitId("session-countdown"),
    ...shot("exam-mock-item"),
    ...answerSteps(steps, WALK_COURSE, unsupported),
    ...waitId(`exam-mock-intro-${second.id}`, 15000),
    ...shot("exam-mock-next-part"),
    `- stopApp`,
    ``,
  ];
  return { yaml: lines.join("\n"), unsupported };
}

