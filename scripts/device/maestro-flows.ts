/** The system document picker: open Downloads if needed and pick the pushed backup. */
function pickBackup(fileName: string): string[] {
  return [
    `- extendedWaitUntil:`,
    `    visible:`,
    `      text: ${q(`(?i).*(${literal(fileName)}|Downloads|Recent).*`)}`,
    `    timeout: 20000`,
    `- runFlow:`,
    `    when:`,
    `      notVisible:`,
    `        text: ${q(literal(fileName))}`,
    `    commands:`,
    `      - tapOn:`,
    `          text: "Show roots"`,
    `          optional: true`,
    `      - tapOn:`,
    `          text: "Downloads"`,
    ...tapText(fileName),
  ];
}

/** Confirm the replace dialog, wait for the success alert, dismiss it. */
function confirmImport(importLabel: string, importedText: string): string[] {
  return [
    `- tapOn:`,
    `    text: ${q(`(?i)${literal(importLabel)}`)}`,
    `- extendedWaitUntil:`,
    `    visible:`,
    `      text: ${q(literal(importedText))}`,
    `    timeout: 20000`,
    ...shot("import-done"),
    `- tapOn:`,
    `    text: "(?i)ok"`,
  ];
}

