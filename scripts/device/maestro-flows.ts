/** Screenshots of every screen in one UI language (the clipped-text review reads these). */
export function screensFlow(ui: UiLang): string {
  const pack = ALL_COURSE_BUNDLES.find((b) => b.id === WALK_COURSE)!.pack;
  const unit = pack.sections[0].units[0];
  const track = examTracksFor(WALK_COURSE)[0];
  const screens: [string, string, string][] = [
    ["learn", "", "learn-section-.*"],
    ["today", "today", "today-start"],
    ["practice", "practice", "practice-review-words"],
    ["profile", "profile", "profile-stat"],
    ["courses", "courses", "courses-course-.*"],
    ["goals", "goals", "overall-level-card"],
    ["guidebook", `guidebook/${encodeURIComponent(unit.id)}`, "guidebook-screen"],
    ["vocabulary", "vocabulary", "vocab-search"],
    ["exam", `exam/${encodeURIComponent(track.id)}`, "exam-overview"],
    ["placement", "placement/intro", "placement-yes"],
    ["privacy", "privacy", "privacy-policy"],
    ["licenses", "licenses", "licenses-screen"],
    ["lesson", `lesson/${encodeURIComponent(unit.lessons[0].id)}`, "session-(continue|check)"],
  ];
  const lines = header(`Screenshots of every screen (${ui} UI).`);
  for (const [name, route, ready] of screens) {
    lines.push(`- stopApp`, ...openLink(route), ...waitId(ready), `- waitForAnimationToEnd`, ...shot(`${ui}-${name}`));
  }
  lines.push(`- stopApp`, ``);
  return lines.join("\n");
}

/** The whole suite: file name → YAML, plus everything that could not be automated. */
export function buildSuite(): { files: Record<string, string>; problems: string[] } {
  for (const bundle of ALL_COURSE_BUNDLES) registerCourseBundle(bundle);
  const files: Record<string, string> = {};
  const problems: string[] = [];
  // courses.tsv: id → bundled clip count (the driver expects player events only where clips ship).
  const courses: string[] = [];
  for (const bundle of ALL_COURSE_BUNDLES) {
    if (bundle.id.startsWith("xx-")) continue;
    courses.push(`${bundle.id}\t${Object.keys(bundle.audio).length}`);
    const lesson = bundle.pack.sections[0].units[0].lessons[0];
    const { yaml, unsupported } = lessonFlow(bundle.id, lesson);
    files[`lesson-${bundle.id}.yaml`] = yaml;
    if (unsupported.length) problems.push(`${bundle.id}: not automatable — ${unsupported.join(", ")}`);
  }
  for (const ui of Object.keys(UI) as UiLang[]) {
    files[`onboarding-${ui}.yaml`] = onboardingFlow(ui, WALK_COURSE);
    files[`screens-${ui}.yaml`] = screensFlow(ui);
    files[`import-${ui}.yaml`] = importFlow(ui, "lft-backup.json");
  }
  const checkpoint = checkpointFlow();
  if (checkpoint.unsupported.length) problems.push(`checkpoint: not automatable — ${checkpoint.unsupported.join(", ")}`);
  files["checkpoint.yaml"] = checkpoint.yaml;
  files["today.yaml"] = todayFlow();
  files["speech-unavailable.yaml"] = speechUnavailableFlow();
  const exam = examMockFlow();
  if (exam.unsupported.length) problems.push(`exam mock: not automatable — ${exam.unsupported.join(", ")}`);
  files["exam-mock.yaml"] = exam.yaml;
  files["export.yaml"] = exportFlow();
  files["profile.yaml"] = profileFlow();
  Object.assign(files, rc3Flows("lft-backup.json"));
  files["courses.tsv"] = `${courses.join("\n")}\n`;
  return { files, problems };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const i = args.indexOf("--out");
  const out = i >= 0 ? args[i + 1] : "e2e/maestro/generated";
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const { files, problems } = buildSuite();
  for (const [name, yaml] of Object.entries(files)) writeFileSync(path.join(out, name), yaml);
  console.log(`${Object.keys(files).length} flows → ${out}`);
  for (const p of problems) console.error(p);
  if (problems.length) process.exit(1);
}
