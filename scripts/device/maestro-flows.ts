export const APP_ID = "com.vansyson1308.learningfrenchwithtracy";
export const SCHEME = "learningfrenchtracy";
/** The course the acceptance walk onboards into: it carries checkpoints, an exam track and daily words. */
export const WALK_COURSE = "es-vi";
const SCORED_CHECKPOINT = "es.checkpoint.section-1";
const SPOKEN_CHECKPOINT = "es.checkpoint.section-4";
const UI = { vi, en } as const;
export type UiLang = keyof typeof UI;

/** Regex-escape a literal for Maestro's text matcher (full-match regex). */
export function literal(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** ASCII fold for typed answers (adb text input is ASCII-only). */
export function asciiFold(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .replace(/[¿¡]/g, "")
    .replace(/[^\x20-\x7e]/g, "");
}

const q = (s: string) => JSON.stringify(s);

// ---- command builders (top-level YAML list items) -------------------------

const tapId = (id: string) => [`- tapOn:`, `    id: ${q(id)}`];
const tapText = (text: string) => [`- tapOn:`, `    text: ${q(literal(text))}`];
const assertId = (id: string) => [`- assertVisible:`, `    id: ${q(id)}`];
const waitId = (id: string, timeout = 30000) => [`- extendedWaitUntil:`, `    visible:`, `      id: ${q(id)}`, `    timeout: ${timeout}`];
const shot = (name: string) => [`- takeScreenshot: ${q(name)}`];
const openLink = (route: string) => [`- openLink: ${q(`${SCHEME}://${route}`)}`];
const scrollTo = (id: string) => [`- scrollUntilVisible:`, `    element:`, `      id: ${q(id)}`, `    direction: DOWN`];
const TAP_CONTINUE = tapId("session-continue");

function header(comment: string): string[] {
  return [`# Generated by scripts/device/maestro-flows.ts — do not edit.`, `# ${comment}`, `appId: ${APP_ID}`, `---`];
}

/** Commands that answer one exercise and press Check; null when the type is not automatable. */
export function answerCommands(ex: Exercise, courseId: string): string[] | null {
  switch (ex.type) {
    case "select":
    case "fillBlank": {
      const opt = ex.options[ex.correct] as string | { text: string };
      return [...tapText(typeof opt === "string" ? opt : opt.text), ...tapId("session-check")];
    }
    case "wordBank":
      return [
        ...ex.answer.flatMap((tok) => [`- tapOn:`, `    id: "wordbank-token"`, `    text: ${q(literal(tok))}`]),
        ...tapId("session-check"),
      ];
    case "match":
      // A match completes itself once every pair is tapped (no Check).
      return ex.pairs.flatMap((p) => [...tapText(p.target), ...tapText(p.native)]);
    case "readingComprehension": {
      // Passages are long: scroll the option card into view; its label may carry an emoji prefix.
      const option = `(\\S+ )?${literal(ex.options[ex.correct].text)}`;
      const selector = [`    id: "option-card"`, `    text: ${q(option)}`];
      return [`- scrollUntilVisible:`, `    element:`, ...selector.map((l) => `  ${l}`), `    direction: DOWN`, `- tapOn:`, ...selector, ...tapId("session-check")];
    }
    case "typeAnswer": {
      const typed = [ex.answer, ...ex.alternatives].map(asciiFold).find((a) => a.length > 0 && checkAnswer(ex, a, courseId));
      if (!typed) return null;
      return [...tapId("type-answer-input"), `- inputText: ${q(typed)}`, `- hideKeyboard`, ...tapId("session-check")];
    }
    default:
      return null;
  }
}

/**
 * Answer a deterministic step plan. Concept cards take one Continue; every
 * exercise is answered correctly, so its post-answer panel takes one
 * Continue (a match advances by itself) and no retry is ever appended.
 */
function answerSteps(steps: readonly SessionStep[], courseId: string, unsupported: string[]): string[] {
  const lines: string[] = [];
  for (const step of steps) {
    if (step.type === "concept") {
      lines.push(...assertId("concept-card"), ...TAP_CONTINUE);
      continue;
    }
    if (step.type !== "exercise") {
      unsupported.push(`${step.stepId} (${step.type})`);
      continue;
    }
    const ex = step.exercise as Exercise;
    const cmds = answerCommands(ex, courseId);
    if (!cmds) {
      unsupported.push(`${ex.id} (${ex.type})`);
      continue;
    }
    lines.push(...assertId(literal(`exercise-${ex.id}`)), ...cmds);
    if (ex.type !== "match") lines.push(...TAP_CONTINUE);
  }
  return lines;
}

/** Lessons run in the active course: switch through the Courses screen first. */
function switchCourse(courseId: string): string[] {
  return [
    `- stopApp`,
    ...openLink("courses"),
    ...scrollTo(`courses-course-${courseId}`),
    ...tapId(`courses-course-${courseId}`),
    ...waitId("learn-section-.*"),
  ];
}

export function lessonFlow(courseId: string, lesson: LessonPack): { yaml: string; unsupported: string[] } {
  const unsupported: string[] = [];
  const lines = [
    ...header(`Complete ${lesson.id} (${courseId}) from the pack's answers.`),
    ...switchCourse(courseId),
    ...openLink(`lesson/${encodeURIComponent(lesson.id)}`),
    ...waitId("session-(continue|check)"),
    ...answerSteps(lessonSteps(lesson), courseId, unsupported),
    ...waitId("session-summary", 15000),
    ...shot(`lesson-${courseId}-summary`),
  ];
  return { yaml: [...lines, ``].join("\n"), unsupported };
}

/** Fresh install (state cleared) → onboarding in the device's UI language → Learn tab. */
export function onboardingFlow(ui: UiLang, courseId: string): string {
  return [
    ...header(`Fresh install → ${ui} onboarding → ${courseId}.`),
    `- launchApp:`,
    `    clearState: true`,
    // The Start button sits below the course grid: wait for the (top) welcome title.
    `- extendedWaitUntil:`,
    `    visible:`,
    `      text: ${q(literal(UI[ui]["onboarding.welcome"]))}`,
    `    timeout: 30000`,
    ...shot(`${ui}-onboarding`),
    ...scrollTo(`onboarding-course-${courseId}`),
    ...tapId(`onboarding-course-${courseId}`),
    ...scrollTo("onboarding-start"),
    ...tapId("onboarding-start"),
    ...waitId("learn-section-.*"),
    ...shot(`${ui}-learn`),
    ``,
  ].join("\n");
}

