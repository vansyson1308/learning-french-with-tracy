/** The first scored checkpoint of the walk course, answered correctly from its first form. */
export function checkpointFlow(): { yaml: string; unsupported: string[] } {
  const checkpoint = checkpointFor(WALK_COURSE, SCORED_CHECKPOINT);
  if (!checkpoint) throw new Error(`missing checkpoint ${SCORED_CHECKPOINT}`);
  const unsupported: string[] = [];
  const steps = buildCheckpointSessionDefinition(WALK_COURSE, checkpoint, 0).steps;
  const lines = [
    ...header(`Sit ${SCORED_CHECKPOINT} (${steps.length} items) and reach its result.`),
    `- stopApp`,
    ...openLink(`checkpoint/${encodeURIComponent(SCORED_CHECKPOINT)}`),
    ...waitId("session-check"),
    ...answerSteps(steps, WALK_COURSE, unsupported),
    ...waitId("checkpoint-results", 15000),
    // Every item answered correctly on the first try: the result must say so.
    `- assertVisible:`,
    `    id: "checkpoint-first-try"`,
    `    text: ${q(`.*${steps.length}/${steps.length}.*`)}`,
    ...shot("checkpoint-result"),
    ``,
  ];
  return { yaml: lines.join("\n"), unsupported };
}

