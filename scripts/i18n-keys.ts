/**
 * Generates src/lib/i18n/keys.ts — the `MessageKey` union — from the
 * English catalogue (the key source of truth). Run after adding keys:
 * `bun scripts/i18n-keys.ts`; `--check` exits 1 when the file is stale
 * (CI). A test also pins the generated union to the catalogue.
 */
import { readFileSync, writeFileSync } from "fs";

import { safeResolve } from "./lib/pipeline";

export const CATALOG_EN = "src/lib/i18n/catalog/en.json";
export const CATALOG_VI = "src/lib/i18n/catalog/vi.json";
export const KEYS_FILE = "src/lib/i18n/keys.ts";

/** A catalogue rendered with sorted keys (deterministic diffs). */
export function renderCatalog(catalog: Record<string, string>): string {
  const sorted: Record<string, string> = {};
  for (const key of Object.keys(catalog).sort()) sorted[key] = catalog[key];
  return `${JSON.stringify(sorted, null, 2)}
`;
}

export function renderKeys(catalog: Record<string, string>): string {
  const keys = Object.keys(catalog).sort();
  const lines = [
    "// GENERATED by scripts/i18n-keys.ts from src/lib/i18n/catalog/en.json — do not edit.",
    "",
    "export type MessageKey =",
    ...keys.map((k, i) => `  | ${JSON.stringify(k)}${i === keys.length - 1 ? ";" : ""}`),
    "",
    `export const MESSAGE_KEY_COUNT = ${keys.length};`,
    "",
  ];
  return lines.join("\n");
}

if (import.meta.main) {
  const catalog = JSON.parse(readFileSync(safeResolve(CATALOG_EN), "utf8")) as Record<string, string>;
  const rendered = renderKeys(catalog);
  const target = safeResolve(KEYS_FILE);
  const check = process.argv.includes("--check");
  for (const rel of [CATALOG_EN, CATALOG_VI]) {
    const raw = readFileSync(safeResolve(rel), "utf8");
    const sorted = renderCatalog(JSON.parse(raw) as Record<string, string>);
    if (raw !== sorted) {
      if (check) {
        console.error(`${rel} is not key-sorted — run: bun scripts/i18n-keys.ts`);
        process.exit(1);
      }
      writeFileSync(safeResolve(rel), sorted);
      console.log(`sorted ${rel}`);
    }
  }
  if (check) {
    const current = (() => {
      try {
        return readFileSync(target, "utf8");
      } catch {
        return "";
      }
    })();
    if (current !== rendered) {
      console.error(`${KEYS_FILE} is stale — run: bun scripts/i18n-keys.ts`);
      process.exit(1);
    }
    console.log(`${KEYS_FILE} up to date (${Object.keys(catalog).length} keys)`);
  } else {
    writeFileSync(target, rendered);
    console.log(`wrote ${KEYS_FILE} (${Object.keys(catalog).length} keys)`);
  }
}
