/**
 * Lexicon authoring from the committed ETL evidence (P3a). Fully offline:
 * reads content/<lang>/lexicon/derived/* (never the raw dumps), the course
 * packs of the target language and the frozen id map, and writes
 *
 *   content/<lang>/lexemes.json          surface → frozen id (ids never change once committed)
 *   content/<lang>/lexicon/lexemes.json  the authored rich lexicon (schema-validated before writing)
 *   content/<lang>/lexicon/REVIEW.md     everything a human still has to check
 *
 * Selection (deterministic): every course-pack word first (gloss identity
 * with the pack is a validator rule), then anchor-listed lemmas by level
 * (N5 before N4, HSK1 before HSK2, A1 before A2), then the frequency
 * population in rank order under a per-topic quota, until --size. Function
 * words (pronouns, prepositions…) fill a small reserved share.
 *
 *   bun scripts/lexicon-author.ts --lang es --size 800
 *   bun scripts/lexicon-author.ts --lang de --size 0 --pool-only   (REVIEW.md statistics only)
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";

import { richLexiconSchema, type PartOfSpeech, type RichLexeme, type TopicValue } from "../content/schema";

import { buildPlugin } from "./lib/languages";
import type { PoolEntry } from "./lib/lexicon-etl/derive";
import { loadPacks, packsForTarget, readJson, safeResolve } from "./lib/pipeline";

function fail(message: string): never {
  console.error(`ERROR ${message}`);
  process.exit(1);
}
const args = process.argv.slice(2);
const opt = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const lang = opt("lang") ?? fail("--lang <code> is required");
const size = Number(opt("size") ?? "0");
const poolOnly = args.includes("--pool-only") || size === 0;
const generator = "scripts/lexicon-author.ts";

type Pool = { entries: PoolEntry[]; criteria: string };
const poolRel = `content/${lang}/lexicon/derived/candidate-pool.json`;
if (!existsSync(safeResolve(poolRel))) fail(`${poolRel} is missing — run the ETL extract first`);
const pool = readJson(poolRel) as Pool;
const anchors = existsSync(safeResolve(`content/${lang}/lexicon/derived/anchors.json`))
  ? (readJson(`content/${lang}/lexicon/derived/anchors.json`) as { status: string; levels: Record<string, Record<string, string>> })
  : { status: "frequency-derived", levels: {} };
const bridge = existsSync(safeResolve("content/en/lexicon/derived/vi-bridge.json"))
  ? (readJson("content/en/lexicon/derived/vi-bridge.json") as { entries: Record<string, string[]> }).entries
  : null;
const plugin = buildPlugin(lang);
const packs = packsForTarget(lang, loadPacks()).filter((p) => p.pack.testOnly !== true);
const nativeCodes = [...new Set(packs.map((p) => p.pack.nativeCode))].sort();

// ---------------------------------------------------------------------------
// Pool statistics (always written; the only output of --pool-only)
// ---------------------------------------------------------------------------
const stats = {
  pool: pool.entries.length,
  content: pool.entries.filter((e) => e.kind === "content").length,
  withEnGloss: pool.entries.filter((e) => e.glosses.en.length > 0).length,
  withViGloss: pool.entries.filter((e) => e.glosses.vi.length > 0).length,
  withExample: pool.entries.filter((e) => e.examples.length > 0).length,
  withIpa: pool.entries.filter((e) => e.ipa !== null).length,
  anchored: pool.entries.filter((e) => Object.keys(e.anchors).length > 0).length,
  usageTagged: pool.entries.filter((e) => e.usageTags.length > 0).length,
  topicEveryday: pool.entries.filter((e) => e.topic === "everyday").length,
};

const reviewDir = safeResolve(`content/${lang}/lexicon`);
mkdirSync(reviewDir, { recursive: true });

if (poolOnly) {
  const lines = [
    `# ${lang} lexicon — pool review (generated by ${generator}, --pool-only)`,
    "",
    "No lexemes are authored for this language yet; this sheet records what the committed",
    `evidence (content/${lang}/lexicon/derived/) can and cannot provide, for the authoring pass of a later milestone.`,
    "",
    `- Pool: ${stats.pool} entries (${stats.content} content, ${stats.pool - stats.content} function words); anchors: ${anchors.status}`,
    `- English gloss: ${stats.withEnGloss} · Vietnamese gloss: ${stats.withViGloss} (the rest would be \`TODO:vi\`) · ≥1 example: ${stats.withExample} · IPA: ${stats.withIpa} · anchored: ${stats.anchored}`,
    `- Usage-tagged (vulgar, slang, obsolete, abbreviation…) — excluded by the author: ${stats.usageTagged}`,
    `- Topic unresolved (\`everyday\`): ${stats.topicEveryday}`,
    "",
    "## Top 40 by measured frequency",
    "",
    ...pool.entries.slice(0, 40).map((e) => `- ${e.lemma} (${e.partOfSpeech}, rank ${e.frequency?.rank ?? "—"}, ${e.frequency?.band ?? "unmeasured"}) — en: ${e.glosses.en[0] ?? "—"} · vi: ${e.glosses.vi[0] ?? "TODO:vi"}`),
    "",
  ];
  writeFileSync(`${reviewDir}/REVIEW.md`, lines.join("\n"));
  console.log(`${lang}: pool-only review written (${stats.pool} entries, vi glosses ${stats.withViGloss})`);
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Selection
// ---------------------------------------------------------------------------
const EXCLUDE_TAGS = new Set(["vulgar", "offensive", "derogatory", "slang", "obsolete", "archaic", "dated", "rare", "abbreviation", "initialism", "acronym", "proper-noun", "misspelling", "alt-of", "nonstandard", "pejorative", "letter", "symbol", "historical", "ethnic"]);
const ANCHOR_ORDER = ["N5", "N4", "HSK1", "HSK2", "A1", "A2", "NGSL-1k"];
const UNIT_TOPICS: Record<string, TopicValue> = {
  animals: "animals",
  family: "family",
  food: "food",
  greetings: "greetings",
  health: "body",
  shopping: "shopping",
  travel: "travel",
  weather: "weather",
  "work & school": "work",
  people: "people",
  places: "places",
  time: "time",
  numbers: "numbers",
  colors: "colors",
  clothing: "clothing",
  home: "home",
  nature: "nature",
  feelings: "feelings",
};

type Selected = { entry: PoolEntry | null; surface: string; lookupForm: string; packGloss: Record<string, string>; packTopic: TopicValue | null; reason: string };

const byKey = new Map(pool.entries.map((e) => [`${e.lemma}|${e.partOfSpeech}`, e]));
const POS_PREFERENCE: PartOfSpeech[] = ["noun", "verb", "adjective", "adverb", "pronoun", "determiner", "preposition", "conjunction", "interjection", "expression", "other"];
function poolFor(lookupForm: string, hadArticle: boolean): PoolEntry | null {
  const prefs = hadArticle ? ["noun", ...POS_PREFERENCE.filter((p) => p !== "noun")] : POS_PREFERENCE;
  for (const pos of prefs) {
    const e = byKey.get(`${lookupForm}|${pos}`);
    if (e) return e;
  }
  return null;
}

const selected: Selected[] = [];
const taken = new Set<string>();
const takeKey = (e: PoolEntry) => `${e.lemma}|${e.partOfSpeech}`;
const rankOf = (e: PoolEntry) => e.frequency?.rank ?? Number.POSITIVE_INFINITY;
// Homographs: of several content readings of one lemma (ser verb / "el ser" noun, poder verb / noun),
// only the best-ranked reading is authored by frequency; the others stay in the pool for a human.
// German capitalises nouns, so its nominalisations differ only in case (haben / das Haben):
// there the readings are grouped case-insensitively.
const readingKey = (lemma: string) => (lang === "de" ? lemma.toLowerCase() : lemma);
const bestReading = new Map<string, PoolEntry>();
for (const e of pool.entries) {
  if (e.kind !== "content") continue;
  const prev = bestReading.get(readingKey(e.lemma));
  if (!prev || rankOf(e) < rankOf(prev)) bestReading.set(readingKey(e.lemma), e);
}
const isSecondaryReading = (e: PoolEntry) => e.kind === "content" && bestReading.get(readingKey(e.lemma)) !== e;

/**
 * Curated exclusions (content/<lang>/lexicon/exclude.json, optional): readings a
 * learner lexicon must not author — subtitle-corpus violence and vulgarity
 * kaikki leaves untagged, ETL artefacts. Keys are `lemma|partOfSpeech`.
 */
const excludeRel = `content/${lang}/lexicon/exclude.json`;
const excluded = new Set<string>(existsSync(safeResolve(excludeRel)) ? (readJson(excludeRel) as { entries: { key: string }[] }).entries.map((x) => x.key) : []);
/** A plural pack surface ("los zapatos") → the singular lemma guess the pool may hold. */
const singularGuesses = (form: string): string[] => {
  const out: string[] = [];
  if (/es$/.test(form)) out.push(form.slice(0, -2), form.slice(0, -2).replace(/c$/, "z"));
  if (/s$/.test(form)) out.push(form.slice(0, -1));
  return out.filter((g) => g.length >= 2);
};

// 1. Course-pack words (every native language of the target).
const packWords = new Map<string, { gloss: Record<string, string>; topic: TopicValue | null }>();
for (const { pack } of packs) {
  for (const section of pack.sections) {
    for (const unit of section.units) {
      const topic = UNIT_TOPICS[unit.title.trim().toLowerCase()] ?? null;
      for (const w of unit.words ?? []) {
        const prev = packWords.get(w.target) ?? { gloss: {}, topic };
        if (prev.gloss[pack.nativeCode] === undefined) prev.gloss[pack.nativeCode] = w.native;
        if (prev.topic === null) prev.topic = topic;
        packWords.set(w.target, prev);
      }
    }
  }
}
// Target sentences the packs already teach (upstream MIT content): the example of last resort,
// and extra evidence for pack words. (target, native) pairs keyed by native code.
const packSentences: { target: string; native: Record<string, string>; key: string }[] = [];
for (const { pack, courseId } of packs) {
  for (const section of pack.sections) {
    for (const unit of section.units) {
      for (const lesson of unit.lessons) {
        for (const ex of lesson.exercises as Record<string, unknown>[]) {
          const type = ex.type as string;
          let target: string | undefined;
          let native: string | undefined;
          if (type === "wordBank" && ex.direction === "targetToNative") {
            target = ex.prompt as string;
            native = (ex.answer as string[]).join(" ");
          } else if (type === "typeAnswer" && ex.mode === "translate" && typeof ex.answer === "string") {
            target = ex.prompt as string;
            native = ex.answer;
          } else if (type === "fillBlank" && typeof ex.sentence === "string" && Array.isArray(ex.options) && typeof ex.correct === "number") {
            target = (ex.sentence as string).replace("___", (ex.options as string[])[ex.correct as number]);
            native = ex.translation as string | undefined;
          }
          if (!target || !native) continue;
          packSentences.push({ target, native: { [pack.nativeCode]: native }, key: `${courseId}:${ex.id as string}` });
        }
      }
    }
  }
}
const packSentenceFor = (lookupForm: string) => {
  const escaped = lookupForm.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`(?:^|[^\\p{L}])${escaped}(?=$|[^\\p{L}])`, "iu");
  return packSentences.filter((s) => re.test(s.target)).sort((a, b) => a.target.length - b.target.length)[0];
};

for (const [surface, { gloss, topic }] of packWords) {
  const { article, rest } = plugin.splitSurfaceArticle(surface);
  let entry = poolFor(rest, article !== null);
  if (!entry) for (const g of singularGuesses(rest)) if ((entry = poolFor(g, article !== null))) break;
  if (entry) taken.add(takeKey(entry));
  selected.push({ entry, surface, lookupForm: rest, packGloss: gloss, packTopic: topic, reason: "course pack word" });
}

const usable = (e: PoolEntry) =>
  !taken.has(takeKey(e)) &&
  e.reason === "ranked" &&
  !isSecondaryReading(e) &&
  e.glosses.en.length > 0 &&
  e.examples.some((x) => x.translations.en !== undefined) &&
  !e.usageTags.some((t) => EXCLUDE_TAGS.has(t)) &&
  !excluded.has(`${e.lemma}|${e.partOfSpeech}`) &&
  !packWords.has(e.lemma);

// 2. Anchor-first.
const anchorRank = (e: PoolEntry) => {
  const levels = Object.values(e.anchors);
  const idx = levels.map((l) => ANCHOR_ORDER.indexOf(l)).filter((i) => i >= 0);
  return idx.length > 0 ? Math.min(...idx) : Number.POSITIVE_INFINITY;
};
const anchored = pool.entries.filter((e) => e.kind === "content" && anchorRank(e) < Number.POSITIVE_INFINITY && usable(e)).sort((a, b) => anchorRank(a) - anchorRank(b) || rankOf(a) - rankOf(b));
for (const e of anchored) {
  if (selected.length >= size) break;
  taken.add(takeKey(e));
  selected.push({ entry: e, surface: "", lookupForm: e.lemma, packGloss: {}, packTopic: null, reason: `anchor ${Object.entries(e.anchors).map(([s, l]) => `${s}:${l}`).join(",")}` });
}

// 3. Frequency fill under a per-topic quota (function words: a reserved share).
const FUNCTION_SHARE = 0.08;
const topicCount = new Map<string, number>();
const topicCap = (topic: string) => Math.ceil(size * (topic === "everyday" ? 0.4 : 0.14));
const functionCap = Math.ceil(size * FUNCTION_SHARE);
let functionTaken = 0;
for (const s of selected) if (s.entry) topicCount.set(s.entry.topic, (topicCount.get(s.entry.topic) ?? 0) + 1);
// The pool lists content words before function words, so the reserved share is taken first
// (in function rank order); otherwise the content fill reaches --size before any function word.
for (const e of pool.entries) {
  if (selected.length >= size || functionTaken >= functionCap) break;
  if (e.kind !== "function" || !usable(e)) continue;
  functionTaken += 1;
  taken.add(takeKey(e));
  topicCount.set(e.topic, (topicCount.get(e.topic) ?? 0) + 1);
  selected.push({ entry: e, surface: "", lookupForm: e.lemma, packGloss: {}, packTopic: null, reason: `function word rank ${rankOf(e)}` });
}
const deferredByTopic: PoolEntry[] = [];
for (const e of pool.entries) {
  if (selected.length >= size) break;
  if (!usable(e)) continue;
  if (e.kind === "function") {
    continue;
  } else if ((topicCount.get(e.topic) ?? 0) >= topicCap(e.topic)) {
    deferredByTopic.push(e);
    continue;
  }
  taken.add(takeKey(e));
  topicCount.set(e.topic, (topicCount.get(e.topic) ?? 0) + 1);
  selected.push({ entry: e, surface: "", lookupForm: e.lemma, packGloss: {}, packTopic: null, reason: `frequency rank ${rankOf(e)}` });
}
// If the quota starved the fill, release the deferred entries in rank order.
for (const e of deferredByTopic) {
  if (selected.length >= size) break;
  if (taken.has(takeKey(e))) continue;
  taken.add(takeKey(e));
  selected.push({ entry: e, surface: "", lookupForm: e.lemma, packGloss: {}, packTopic: null, reason: `frequency rank ${rankOf(e)} (topic quota released)` });
}

// ---------------------------------------------------------------------------
// Assembly
// ---------------------------------------------------------------------------
const frozenRel = `content/${lang}/lexemes.json`;
const frozen: Record<string, string> = existsSync(safeResolve(frozenRel)) ? (readJson(frozenRel) as Record<string, string>) : {};
const usedIds = new Set(Object.values(frozen));
const slugOf = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const ARTICLE_OF: Record<string, Partial<Record<string, string>>> = {
  es: { masculine: "el", feminine: "la" },
  it: { masculine: "il", feminine: "la" },
  pt: { masculine: "o", feminine: "a" },
  de: { masculine: "der", feminine: "die", neuter: "das" },
  fr: { masculine: "le", feminine: "la" },
};
const review = { todoVi: [] as string[], bridgedVi: [] as string[], sourceVi: [] as string[], noPool: [] as string[], noExample: [] as string[], unknownGender: [] as string[], untranslatedExamples: [] as string[], confusables: [] as string[], topicUnresolved: [] as string[], glossEdited: [] as string[] };

function englishGloss(e: PoolEntry): string {
  const raw = e.glosses.en[0];
  // Learner gloss: the first sense, at most two of its comma-separated readings, no parenthetical qualifiers.
  let g = raw.split(";")[0].split(" (")[0].split(",").slice(0, 2).map((x) => x.trim()).filter((x) => x.length > 0).join(", ");
  if (e.partOfSpeech === "verb" && !/^to /.test(g)) g = `to ${g}`;
  if (e.partOfSpeech === "noun" && !/^(a|an|the|to) /.test(g) && !/^[A-Z]/.test(g)) g = `the ${g}`;
  if (g !== raw) review.glossEdited.push(`${e.lemma}: "${raw}" → "${g}"`);
  return g;
}

function vietnameseGloss(e: PoolEntry, id: string): string {
  if (e.glosses.vi.length > 0) {
    review.sourceVi.push(`${id}: "${e.glosses.vi[0]}" (en: ${e.glosses.en[0] ?? "—"})`);
    return e.glosses.vi[0];
  }
  if (bridge) {
    const en = e.glosses.en[0]?.split(";")[0].split(" (")[0].replace(/^to /, "").trim().toLowerCase();
    const hit = en ? (bridge[`${en}|${e.partOfSpeech}`] ?? bridge[`${en}|noun`] ?? bridge[`${en}|verb`] ?? bridge[`${en}|adjective`]) : undefined;
    if (hit && hit.length > 0) {
      review.bridgedVi.push(`${id}: "${en}" → "${hit[0]}" (via the English Wiktionary translation table — verify)`);
      return hit[0];
    }
  }
  review.todoVi.push(id);
  return "TODO:vi";
}

const lexemes: RichLexeme[] = [];
const idBySurface = new Map<string, string>();
const seenSurfaces = new Set<string>();
for (const sel of selected) {
  const e = sel.entry;
  const pos: PartOfSpeech = e?.partOfSpeech ?? (sel.packGloss.en && /^to /.test(sel.packGloss.en) ? "verb" : "noun");
  let gender: RichLexeme["gender"] = pos === "noun" ? (e?.gender ?? "unknown") : undefined;
  if (pos === "noun" && plugin.articleRules) {
    // Gender = what the evidence agrees on: the source reading, the course surface's own article
    // (the learner sees it) and the determiners in the examples. Any disagreement — or an epicene
    // source reading — is "both" (el/la estudiante); nothing at all stays "unknown".
    const votes = new Set<"masculine" | "feminine" | "neuter">();
    const packArticle = sel.surface === "" ? null : plugin.splitSurfaceArticle(sel.surface).article;
    const silent = packArticle && plugin.articleRules.neutralBefore?.articles.includes(packArticle) && plugin.articleRules.neutralBefore.noun.test(sel.lookupForm);
    const proves = packArticle && !silent ? plugin.articleRules.gender[packArticle] : undefined;
    if (proves) votes.add(proves);
    for (const v of plugin.genderEvidenceInText((e?.examples ?? []).map((x) => x.target).join("\n"), sel.lookupForm)) votes.add(v);
    if (gender === "masculine" || gender === "feminine" || gender === "neuter") votes.add(gender);
    if (gender === "both" || votes.size > 1) gender = "both";
    else if (votes.size === 1) gender = [...votes][0];
    else gender = "unknown";
  }
  let surface = sel.surface;
  if (surface === "" && e) {
    const article = pos === "noun" && gender && gender !== "both" && gender !== "unknown" ? ARTICLE_OF[lang]?.[gender] : undefined;
    surface = article ? `${article} ${e.lemma}` : e.lemma;
  }
  if (seenSurfaces.has(surface)) continue;
  seenSurfaces.add(surface);
  const baseSlug = slugOf(sel.lookupForm);
  let id = frozen[surface] ?? `${lang}:w:${baseSlug}`;
  if (frozen[surface] === undefined) {
    const variants = [id, `${lang}:w:${baseSlug}-${gender === "feminine" ? "f" : gender === "masculine" ? "m" : pos}`, `${lang}:w:${baseSlug}-${pos}`];
    id = variants.find((v) => !usedIds.has(v)) ?? id;
    let n = 2;
    while (usedIds.has(id)) id = `${lang}:w:${baseSlug}-${pos}-${n++}`;
  }
  usedIds.add(id);
  idBySurface.set(surface, id);

  if (!e) review.noPool.push(`${id} ("${surface}") — pack word absent from the candidate pool: pack gloss only, no IPA/frequency`);
  if (pos === "noun" && gender === "unknown") review.unknownGender.push(id);
  const glosses: Record<string, string> = {};
  for (const native of nativeCodes) if (sel.packGloss[native] !== undefined) glosses[native] = sel.packGloss[native];
  if (glosses.en === undefined && e) glosses.en = englishGloss(e);
  if (glosses.vi === undefined) glosses.vi = e ? vietnameseGloss(e, id) : "TODO:vi";
  if (glosses.vi === "TODO:vi" && !e) review.todoVi.push(id);
  const examples: RichLexeme["examples"] = [];
  for (const ex of e?.examples ?? []) {
    if (ex.translations.en === undefined) continue;
    if (examples.some((x) => x.target === ex.target)) continue;
    const translations: Record<string, string> = { en: ex.translations.en, vi: ex.translations.vi ?? "TODO:vi" };
    if (translations.vi === "TODO:vi") review.untranslatedExamples.push(`${id}: "${ex.target}"`);
    examples.push({ target: ex.target, translations, source: ex.source, key: ex.key });
    if (examples.length >= 3) break;
  }
  if (examples.length === 0 || Object.keys(sel.packGloss).length > 0) {
    const ps = packSentenceFor(sel.lookupForm);
    if (ps && !examples.some((x) => x.target === ps.target) && ps.native.en !== undefined) {
      const translations: Record<string, string> = { en: ps.native.en, vi: ps.native.vi ?? "TODO:vi" };
      if (translations.vi === "TODO:vi") review.untranslatedExamples.push(`${id}: "${ps.target}"`);
      examples.unshift({ target: ps.target, translations, source: "upstream-lingo-lessons", key: ps.key });
      if (examples.length > 3) examples.pop();
    }
  }
  if (examples.length === 0) review.noExample.push(`${id} ("${surface}")`);
  const topic: TopicValue = sel.packTopic ?? (e?.topic as TopicValue | undefined) ?? "everyday";
  if (topic === "everyday" && (!e || e.topicMatched === null)) review.topicUnresolved.push(id);
  const sourceRefs: RichLexeme["sourceRefs"] = [];
  if (e) sourceRefs.push({ source: "kaikki-en", key: `${e.lemma}|${e.sourcePos}` });
  if (e && e.glosses.vi.length > 0) sourceRefs.push({ source: "kaikki-vi", key: `${e.lemma}|${e.sourcePos}` });
  if (e?.frequency) sourceRefs.push({ source: "frequencywords", key: e.lemma });
  if (Object.keys(sel.packGloss).length > 0) sourceRefs.push({ source: "upstream-lingo-lessons", key: surface });
  sourceRefs.push({ source: "original-lexicon-etl" });
  lexemes.push({
    id,
    surface,
    lemma: sel.lookupForm,
    lookupForm: sel.lookupForm,
    partOfSpeech: pos,
    ...(gender !== undefined ? { gender } : {}),
    glosses,
    ...(e?.ipa ? { pronunciation: { value: e.ipa, notation: "ipa", source: "kaikki-en" } } : {}),
    ...(e?.frequency ? { frequency: { source: "frequencywords", rawValue: e.frequency.perMillion, rank: e.frequency.rank, band: e.frequency.band } } : {}),
    topic,
    examples,
    sourceRefs,
  });
}

// Confusables: same part of speech, close spelling (symmetric, ≤ 3 each).
function distance(a: string, b: string): number {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array<number>(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return dp[a.length][b.length];
}
const fold = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
const confusables = new Map<string, Set<string>>();
for (let i = 0; i < lexemes.length; i++) {
  for (let j = i + 1; j < lexemes.length; j++) {
    const a = lexemes[i];
    const b = lexemes[j];
    if (a.partOfSpeech !== b.partOfSpeech) continue;
    const fa = fold(a.lookupForm);
    const fb = fold(b.lookupForm);
    if (fa.length < 4 || fb.length < 4 || Math.abs(fa.length - fb.length) > 2) continue;
    if (distance(fa, fb) <= 1 || (fa.slice(0, 4) === fb.slice(0, 4) && distance(fa, fb) <= 2)) {
      const sa = confusables.get(a.id) ?? new Set();
      const sb = confusables.get(b.id) ?? new Set();
      if (sa.size >= 3 || sb.size >= 3) continue;
      sa.add(b.id);
      sb.add(a.id);
      confusables.set(a.id, sa);
      confusables.set(b.id, sb);
      review.confusables.push(`${a.id} ↔ ${b.id}`);
    }
  }
}
for (const lex of lexemes) {
  const set = confusables.get(lex.id);
  if (set && set.size > 0) lex.relations = { confusables: [...set].sort() };
}

