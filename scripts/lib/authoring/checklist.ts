/**
 * Native review checklist (P3c): every learner-facing string of a course
 * (pack titles, descriptions, guidebooks, word glosses, exercise native
 * text; every native-text record of the rich layers) as a checkbox list
 * grouped by authoring step, for the native reviewer. The compile gate
 * (`content/courses/<id>.profile.json` → `review` or `allowUnreviewed`)
 * is enforced by the validators; this file is what the reviewer works
 * through before signing.
 */

import { existsSync } from "fs";

import type { PackSource } from "../../../content/schema";
import { exerciseNativeFieldPaths, getPath } from "../native-fields";
import { readJson, safeResolve } from "../pipeline";

type Line = { group: string; id: string; text: string };

function walkNative(value: unknown, native: string, path: string, out: Line[], group: string): void {
  if (Array.isArray(value)) {
    value.forEach((v, i) => walkNative(v, native, `${path}[${i}]`, out, group));
    return;
  }
  if (value && typeof value === "object") {
    const rec = value as Record<string, unknown>;
    if (typeof rec[native] === "string" && Object.keys(rec).every((k) => /^[a-z]{2,3}$/.test(k))) {
      out.push({ group, id: path, text: rec[native] as string });
      return;
    }
    for (const [k, v] of Object.entries(rec)) walkNative(v, native, `${path}.${k}`, out, group);
  }
}

export function collectChecklist(courseId: string): Line[] {
  const pack = readJson(`content/courses/${courseId}.json`) as PackSource;
  const lang = pack.targetCode;
  const native = pack.nativeCode;
  const out: Line[] = [];
  for (const s of pack.sections) {
    out.push({ group: "units", id: s.id, text: s.title });
    for (const u of s.units) {
      out.push({ group: "units", id: `${u.id}.title`, text: u.title });
      if (u.description) out.push({ group: "units", id: `${u.id}.description`, text: u.description });
      if (u.guidebook) out.push({ group: "units", id: `${u.id}.guidebook`, text: `${u.guidebook.slice(0, 120).replace(/\n/g, " ")}… (${u.guidebook.length} chars)` });
      for (const w of u.words) out.push({ group: "lexicon-review", id: `${u.id}:${w.target}`, text: w.native });
      for (const l of u.lessons) {
        out.push({ group: "lessons", id: `${l.id}.title`, text: l.title });
        for (const ex of l.exercises) {
          for (const p of exerciseNativeFieldPaths(ex as Record<string, unknown>)) {
            const text = getPath(ex, p);
            if (typeof text === "string") out.push({ group: "lessons", id: `${ex.id}.${p}`, text });
          }
        }
      }
    }
  }
  const rich: [string, string][] = [
    ["objectives", `content/${lang}/assessment/objectives.json`],
    ["concepts", `content/${lang}/pedagogy/concepts.json`],
    ["concepts", `content/${lang}/pedagogy/paradigms.json`],
    ["readings", `content/${lang}/reception/reading.json`],
    ["speech", `content/${lang}/speech/items.json`],
    ["writing", `content/${lang}/writing/tasks.json`],
    ["scenarios", `content/${lang}/interaction/scenarios.json`],
    ["checkpoints", `content/${lang}/assessment/checkpoints.json`],
    ["placement", `content/${lang}/assessment/placement.json`],
    ["lexicon-review", `content/${lang}/lexicon/lexemes.json`],
  ];
  for (const [group, rel] of rich) if (existsSync(safeResolve(rel))) walkNative(readJson(rel), native, rel.split("/").pop()!.replace(".json", ""), out, group);
  return out;
}

export function renderChecklist(courseId: string, lines: Line[]): string {
  const groups = new Map<string, Line[]>();
  for (const l of lines) groups.set(l.group, [...(groups.get(l.group) ?? []), l]);
  const out = [
    `# Review checklist — ${courseId}`,
    "",
    `Generated by \`bun scripts/author.ts checklist --course ${courseId}\`. ${lines.length} learner-facing strings. The native reviewer ticks every line (or fixes the source and re-runs the ingest), then records \`review: { native: "<name>", date: "YYYY-MM-DD" }\` in \`content/courses/${courseId}.profile.json\`. Until then the course compiles only with \`allowUnreviewed: true\` and an entry in release/KNOWN_LIMITATIONS.md.`,
    "",
  ];
  for (const [group, list] of groups) {
    out.push(`## ${group} (${list.length})`, "");
    for (const l of list) out.push(`- [ ] \`${l.id}\` — ${l.text.replace(/\n/g, " ")}`);
    out.push("");
  }
  return out.join("\n");
}
