/**
 * Per-course content bundles (P3g B). The app used to import every course's
 * pack, artifacts and audio map at start-up (one 7.4 MB web entry). The
 * compiler now emits, per course:
 *
 *   src/content/audio/<audioCourseId>.ts   that course's slice of the pinned
 *                                          audio manifest (static require()s)
 *   src/content/courses/<courseId>.ts      { pack, artifacts, audio } — static
 *                                          imports inside, Metro-friendly
 *   src/content/course-loaders.ts          courseId → () => import("./courses/<id>")
 *                                          (a separate chunk on web, a lazily
 *                                          evaluated module on native)
 *   src/content/course-bundles.ts          every bundle, statically — for tests
 *                                          and scripts only; the app never imports
 *                                          it (import-graph test)
 *
 * src/content/audio-manifest.ts stays the pinned source of truth written by
 * `audio.ts apply`; the per-course slices are derived from it.
 */

import path from "path";

import type { CourseProfile } from "../../src/lib/course-profile";

const HEADER = "// Generated by scripts/compile-content.ts — do not edit.";
const ident = (id: string) => id.replace(/[^a-zA-Z0-9]/g, "_");

function importFrom(fromDir: string, rel: string): string {
  const spec = path.posix.relative(fromDir, rel.replace(/\.(ts|tsx)$/, ""));
  return spec.startsWith(".") ? spec : `./${spec}`;
}

/** Entries of src/content/audio-manifest.ts (`"<course>:<text>": require("<file>")`). */
export function parseAudioManifest(text: string): { key: string; file: string }[] {
  const out: { key: string; file: string }[] = [];
  for (const m of text.matchAll(/^\s*("(?:[^"\\]|\\.)*"): require\(("(?:[^"\\]|\\.)*")\),$/gm)) {
    out.push({ key: JSON.parse(m[1]) as string, file: JSON.parse(m[2]) as string });
  }
  return out;
}

/** One course's slice; `file` paths are rebased from src/content/ to src/content/audio/. */
export function renderAudioSlice(courseId: string, entries: { key: string; file: string }[]): string {
  const mine = entries.filter((e) => e.key.startsWith(`${courseId}:`)).sort((a, b) => a.key.localeCompare(b.key));
  const lines = [
    HEADER,
    `// Bundled pack/lexicon audio of ${courseId}: its slice of src/content/audio-manifest.ts`,
    "// (provenance: release/AUDIO_PROVENANCE_FINAL.md). Keys are `<courseId>:<text>`.",
    "export const AUDIO: Record<string, number> = {",
    ...mine.map((e) => `  ${JSON.stringify(e.key)}: require(${JSON.stringify(path.posix.join("..", e.file))}),`),
    "};",
  ];
  return `${lines.join("\n")}\n`;
}

/** Courses whose audio slice is non-empty. */
export function audioCourseIds(entries: { key: string }[]): string[] {
  return [...new Set(entries.map((e) => e.key.slice(0, e.key.indexOf(":"))))].filter((id) => id.length > 0).sort();
}

export function renderCourseModule(root: string, profile: CourseProfile, packRel: string, audioCourses: Set<string>): string {
  const dir = `${root}/courses`;
  const audioCourse = profile.audioCourseId ?? profile.id;
  const hasAudio = audioCourses.has(audioCourse);
  const lines = [
    HEADER,
    `// Course bundle of ${profile.id}: pack + artifacts + bundled audio, loaded on demand (src/content/course-loaders.ts).`,
    `import pack from "${importFrom(dir, packRel)}";`,
    `import { ARTIFACTS } from "${importFrom(dir, `${root}/artifacts/${profile.id}`)}";`,
    ...(hasAudio ? [`import { AUDIO } from "${importFrom(dir, `${root}/audio/${audioCourse}`)}";`] : []),
    `import type { CourseBundle } from "${importFrom(dir, "src/lib/course-bundle")}";`,
    `import type { Pack } from "${importFrom(dir, "src/lib/types")}";`,
    "",
    `export const COURSE: CourseBundle = { id: ${JSON.stringify(profile.id)}, pack: pack as Pack, artifacts: ARTIFACTS, audio: ${hasAudio ? "AUDIO" : "{}"} };`,
    "",
  ];
  return lines.join("\n");
}

export function renderCourseLoaders(root: string, courseIds: string[]): string {
  const lines = [
    HEADER,
    "// One dynamic import per course: a separate chunk on web, evaluated on first use on native.",
    `import type { CourseBundle } from "${importFrom(root, "src/lib/course-bundle")}";`,
    "",
    "export const COURSE_LOADERS: Record<string, () => Promise<CourseBundle>> = {",
    ...courseIds.map((id) => `  ${JSON.stringify(id)}: () => import("./courses/${id}").then((m) => m.COURSE),`),
    "};",
    "",
  ];
  return lines.join("\n");
}

export function renderCourseBundlesStatic(root: string, courseIds: string[]): string {
  const lines = [
    HEADER,
    "// Every course bundle, statically. Tests and scripts only — the app loads courses",
    "// through course-loaders.ts (enforced by src/lib/__tests__/course-bundle.test.ts).",
    ...courseIds.map((id) => `import { COURSE as ${ident(id)} } from "./courses/${id}";`),
    `import type { CourseBundle } from "${importFrom(root, "src/lib/course-bundle")}";`,
    "",
    "export const ALL_COURSE_BUNDLES: CourseBundle[] = [",
    ...courseIds.map((id) => `  ${ident(id)},`),
    "];",
    "",
  ];
  return lines.join("\n");
}
