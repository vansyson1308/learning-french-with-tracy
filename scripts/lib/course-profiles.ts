/**
 * Course-profile compiler (P1b, per artifact root since P1c). From the
 * packs and the list of compiled artifacts it derives one CourseProfile
 * per course, emits:
 *
 *   <root>/course-profiles.json      the registry the runtime reads
 *   <root>/ids/<code>.json + index   stable-id registries per language
 *   <root>/artifacts/<courseId>.ts   static imports of that course's artifacts
 *   <root>/artifacts/index.ts        courseId → artifacts
 *   <root>/lexicon/db-assets.ts      language → prebuilt SQLite asset (native-only import)
 *   <root>/flags.ts                  courseId → round flag asset
 *
 * `root` is src/content for shipped courses and src/content/test-only for
 * test-only courses (never imported by the app). Capabilities derive from
 * which artifacts exist for the course's TARGET language;
 * content/courses/<id>.profile.json may add an explicit `enabled` override
 * (e.g. fsrs for a legacy course). Deterministic.
 */

import { existsSync } from "fs";
import path from "path";

import { CourseProfileOverrideSchema, type PackSource } from "../../content/schema";
import type { CourseArtifactPaths, CourseCapabilities, CourseProfile } from "../../src/lib/course-profile";

import { buildLanguage } from "./languages";
import { canonicalJson, readJson, safeResolve, type CompiledFile } from "./pipeline";

export type LexiconDbInfo = { name: string; contentHash: string };

const HEADER = "// Generated by scripts/compile-content.ts — do not edit.";

/** Artifact relPath conventions per target language (the compiler's own output names). */
function artifactPathsFor(
  root: string,
  code: string,
  present: Set<string>,
  db: LexiconDbInfo | undefined
): CourseArtifactPaths {
  const pick = (rel: string) => (present.has(rel) ? rel : undefined);
  const out: CourseArtifactPaths = {
    ids: pick(`${root}/ids/${code}.json`),
    lexiconIndex: pick(`${root}/lexicon/${code}-index.json`),
    lexiconFallback: pick(`${root}/lexicon/${code}-web-fallback.json`),
    lexiconDb: db ? `assets/lexicon/${db.name}` : undefined,
    concepts: pick(`${root}/concepts/${code}-concepts.json`),
    objectives: pick(`${root}/assessment/${code}-objectives.json`),
    checkpoints: pick(`${root}/assessment/${code}-checkpoints.json`),
    placement: pick(`${root}/assessment/${code}-placement.json`),
    attainment: pick(`${root}/assessment/${code}-attainment.json`),
    claim: pick(`${root}/assessment/${code}-claim.json`),
    listening: pick(`${root}/reception/${code}-listening.json`),
    reading: pick(`${root}/reception/${code}-reading.json`),
    clipAssets: pick(`${root}/reception/${code}-clip-assets.ts`),
    speech: pick(`${root}/speech/${code}-speech-items.json`),
    writing: pick(`${root}/writing/${code}-writing.json`),
    scenarios: pick(`${root}/interaction/${code}-scenarios.json`),
  };
  return Object.fromEntries(Object.entries(out).filter(([, v]) => v !== undefined)) as CourseArtifactPaths;
}

function deriveCapabilities(a: CourseArtifactPaths): CourseCapabilities {
  const has = (k: keyof CourseArtifactPaths) => a[k] !== undefined;
  const fsrs = has("ids");
  return {
    fsrs,
    dailySession: fsrs && has("lexiconIndex"),
    lexicon: has("lexiconIndex") && has("lexiconFallback"),
    concepts: has("concepts"),
    placement: has("placement"),
    checkpoints: has("checkpoints"),
    goals: has("objectives") && has("attainment") && has("claim"),
    listening: has("listening") && has("clipAssets"),
    reading: has("reading"),
    speaking: has("speech"),
    writing: has("writing"),
    conversation: has("scenarios"),
  };
}

function readOverride(courseId: string): Partial<CourseCapabilities> {
  const rel = `content/courses/${courseId}.profile.json`;
  if (!existsSync(safeResolve(rel))) return {};
  return CourseProfileOverrideSchema.parse(readJson(rel)).enabled ?? {};
}

export function deriveProfiles(args: {
  packs: PackSource[];
  presentRelPaths: Iterable<string>;
  lexiconDbs: Record<string, LexiconDbInfo>;
  artifactRoot?: string;
}): Record<string, CourseProfile> {
  const root = args.artifactRoot ?? "src/content";
  const present = new Set(args.presentRelPaths);
  const profiles: Record<string, CourseProfile> = {};
  for (const pack of [...args.packs].sort((a, b) => a.id.localeCompare(b.id))) {
    const lang = buildLanguage(pack.targetCode);
    const artifacts = artifactPathsFor(root, pack.targetCode, present, args.lexiconDbs[pack.targetCode]);
    const capabilities = { ...deriveCapabilities(artifacts), ...readOverride(pack.id) };
    profiles[pack.id] = {
      id: pack.id,
      targetCode: pack.targetCode,
      nativeCode: pack.nativeCode,
      targetLanguage: pack.targetLanguage,
      nativeLanguage: pack.nativeLanguage,
      flag: pack.flag,
      flagAsset: lang.flagAsset,
      recognitionLocale: lang.recognitionLocale,
      ttsLocale: lang.ttsLocale,
      script: lang.script,
      idPrefix: artifacts.ids ? `${pack.targetCode}:w:` : "",
      legacyIdPrefix: artifacts.ids ? `${pack.targetCode}:legacy:` : "",
      capabilities,
      artifacts,
    };
  }
  return profiles;
}

const ident = (id: string) => id.replace(/[^a-zA-Z0-9]/g, "_");

/** Import specifier from `fromDir` to a repo-relative module path (POSIX, no extension for .ts). */
function importFrom(fromDir: string, rel: string): string {
  const spec = path.posix.relative(fromDir, rel.replace(/\.ts$/, ""));
  return spec.startsWith(".") ? spec : `./${spec}`;
}

function renderArtifactModule(root: string, profile: CourseProfile): string {
  const a = profile.artifacts;
  const dir = `${root}/artifacts`;
  const lines: string[] = [HEADER, `// Static artifact imports for ${profile.id} (Metro needs static requires).`];
  const fields: string[] = [];
  const add = (key: keyof CourseArtifactPaths, rel: string | undefined, named?: string) => {
    if (!rel) return;
    const spec = importFrom(dir, rel);
    if (named) {
      lines.push(`import { ${named} as ${key} } from "${spec}";`);
    } else {
      lines.push(`import ${key} from "${spec}";`);
    }
    fields.push(key);
  };
  add("ids", a.ids);
  add("lexiconIndex", a.lexiconIndex);
  add("lexiconFallback", a.lexiconFallback);
  add("concepts", a.concepts);
  add("objectives", a.objectives);
  add("checkpoints", a.checkpoints);
  add("placement", a.placement);
  add("attainment", a.attainment);
  add("claim", a.claim);
  add("listening", a.listening);
  add("reading", a.reading);
  add("clipAssets", a.clipAssets, "RECEPTION_CLIP_ASSETS");
  add("speech", a.speech);
  add("writing", a.writing);
  add("scenarios", a.scenarios);
  lines.push(`import type { CourseArtifacts } from "${importFrom(dir, "src/lib/content-registry")}";`, "");
  lines.push(`export const ARTIFACTS: CourseArtifacts = {${fields.length ? ` ${fields.join(", ")} ` : ""}};`, "");
  return lines.join("\n");
}

function renderArtifactsIndex(root: string, courseIds: string[]): string {
  const dir = `${root}/artifacts`;
  const imports = courseIds.map((id) => `import { ARTIFACTS as ${ident(id)} } from "./${id}";`).join("\n");
  const entries = courseIds.map((id) => `  "${id}": ${ident(id)},`).join("\n");
  return `${HEADER}\n${imports}\nimport type { CourseArtifacts } from "${importFrom(dir, "src/lib/content-registry")}";\n\nexport const COURSE_ARTIFACTS: Record<string, CourseArtifacts> = {\n${entries}\n};\n`;
}

function renderIdsIndex(root: string, codes: string[]): string {
  const dir = `${root}/ids`;
  const imports = codes.map((c) => `import ${ident(c)} from "./${c}.json";`).join("\n");
  const entries = codes.map((c) => `  ${JSON.stringify(c)}: ${ident(c)},`).join("\n");
  return `${HEADER}\nimport type { IdRegistry } from "${importFrom(dir, "src/lib/learning/ids")}";\n${imports}\n\nexport const ID_REGISTRIES: Record<string, IdRegistry> = {\n${entries}\n};\n`;
}

function renderDbAssets(root: string, dbs: Record<string, LexiconDbInfo>): string {
  const dir = `${root}/lexicon`;
  const entries = Object.keys(dbs)
    .sort()
    .map(
      (code) =>
        `  ${JSON.stringify(code)}: { name: ${JSON.stringify(dbs[code].name)}, contentHash: ${JSON.stringify(dbs[code].contentHash)}, asset: require("${importFrom(dir, `assets/lexicon/${dbs[code].name}`)}") },`
    )
    .join("\n");
  return `${HEADER}
/**
 * Versioned lexicon database assets, one per TARGET language. The filename
 * embeds the content hash, so a content change ships as a NEW asset name —
 * a previously copied database is never overwritten in place. Import this
 * module only from native-only code paths (the web bundle must not pull
 * the assets).
 */
export const LEXICON_DB_ASSETS: Record<string, { name: string; contentHash: string; asset: number }> = {
${entries}
};
`;
}

function renderFlags(root: string, profiles: Record<string, CourseProfile>): string {
  const entries = Object.values(profiles)
    .map((p) => `  "${p.id}": require("${importFrom(root, `assets/images/flags/${p.flagAsset}.svg`)}"),`)
    .join("\n");
  return `${HEADER}
/** Round country flags per course (HatScripts/circle-flags, MIT), from each profile's flagAsset. */
export const FLAG_ASSETS: Record<string, number> = {
${entries}
};
`;
}

/**
 * Every profile-derived artifact. `files` is the compiler's list so far
 * (used to see which artifacts exist); the id registries are generated here
 * from content/<code>/lexemes.json for every language that has one.
 */
export function compileCourseProfileArtifacts(args: {
  packs: PackSource[];
  files: CompiledFile[];
  lexiconDbs: Record<string, LexiconDbInfo>;
  /** language code → frozen surface→id map */
  idMaps: Record<string, Record<string, string>>;
  /** src/content (shipped) or src/content/test-only. */
  artifactRoot?: string;
}): { files: CompiledFile[]; profiles: Record<string, CourseProfile> } {
  const root = args.artifactRoot ?? "src/content";
  const out: CompiledFile[] = [];
  const idCodes = Object.keys(args.idMaps).sort();
  for (const code of idCodes) {
    out.push({
      relPath: `${root}/ids/${code}.json`,
      contents: canonicalJson({
        language: code,
        prefix: `${code}:w:`,
        legacyPrefix: `${code}:legacy:`,
        surfaceToId: args.idMaps[code],
      }),
    });
  }
  out.push({ relPath: `${root}/ids/index.ts`, contents: renderIdsIndex(root, idCodes) });

  const present = [...args.files.map((f) => f.relPath), ...out.map((f) => f.relPath)];
  const profiles = deriveProfiles({ packs: args.packs, presentRelPaths: present, lexiconDbs: args.lexiconDbs, artifactRoot: root });
  for (const p of Object.values(profiles)) {
    for (const flag of [p.flagAsset]) {
      if (!existsSync(safeResolve(`assets/images/flags/${flag}.svg`))) {
        throw new Error(`${p.id}: flag asset assets/images/flags/${flag}.svg is missing`);
      }
    }
  }
  const courseIds = Object.keys(profiles).sort();
  // The onboarding default is data too: the course with the most enabled
  // capabilities (ties broken by id). Today that is the complete French course;
  // it moves to fr-vi by content, never by a code edit.
  const defaultCourseId = [...courseIds].sort((a, b) => {
    const score = (id: string) => Object.values(profiles[id].capabilities).filter(Boolean).length;
    return score(b) - score(a) || a.localeCompare(b);
  })[0];
  out.push({
    relPath: `${root}/course-profiles.json`,
    contents: canonicalJson({ version: 1, defaultCourseId, profiles }),
  });
  for (const id of courseIds) {
    out.push({ relPath: `${root}/artifacts/${id}.ts`, contents: renderArtifactModule(root, profiles[id]) });
  }
  out.push({ relPath: `${root}/artifacts/index.ts`, contents: renderArtifactsIndex(root, courseIds) });
  out.push({ relPath: `${root}/lexicon/db-assets.ts`, contents: renderDbAssets(root, args.lexiconDbs) });
  out.push({ relPath: `${root}/flags.ts`, contents: renderFlags(root, profiles) });
  return { files: out, profiles };
}
